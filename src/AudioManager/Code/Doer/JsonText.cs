using System.Globalization;
using System.Text;

namespace AudioManager
{
    /// <summary>
    /// The one JSON string escaper for hand-built records. Control characters (tab, CR, backspace, form feed and
    /// anything else below space) are escaped, never dropped, so a raw message can not produce a malformed record.
    /// </summary>
    internal static class JsonText
    {
        /// <summary>Quoted JSON literal for s, or the literal null.</summary>
        public static string Quote(string s)
        {
            if (s == null) return "null";
            var sb = new StringBuilder(s.Length + 2);
            sb.Append('"');
            foreach (char c in s)
            {
                switch (c)
                {
                    case '\\': sb.Append("\\\\"); break;
                    case '"': sb.Append("\\\""); break;
                    case '\b': sb.Append("\\b"); break;
                    case '\f': sb.Append("\\f"); break;
                    case '\n': sb.Append("\\n"); break;
                    case '\r': sb.Append("\\r"); break;
                    case '\t': sb.Append("\\t"); break;
                    default:
                        if (c < ' ') sb.Append("\\u").Append(((int)c).ToString("x4", CultureInfo.InvariantCulture));
                        else sb.Append(c);
                        break;
                }
            }
            sb.Append('"');
            return sb.ToString();
        }
    }
}
